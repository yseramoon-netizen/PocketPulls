const FALLBACK_RUNE = "10101/01010/10101/00100/10101/01010/10101";
const PIXEL_STEP_EM = 0.105;

export function getPixelRuneShadow(character: string): string {
  const pattern =
    PIXEL_RUNE_ALPHABET[character.toUpperCase()] || FALLBACK_RUNE;

  return pattern
    .split("/")
    .flatMap((row, y) =>
      Array.from(row).flatMap((pixel, x) =>
        pixel === "1"
          ? [`${(x * PIXEL_STEP_EM).toFixed(3)}em ${(y * PIXEL_STEP_EM).toFixed(3)}em 0 currentColor`]
          : [],
      ),
    )
    .join(", ");
}

